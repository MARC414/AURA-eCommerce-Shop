/**
 * What is actually in dist/, checked rather than assumed.
 *
 * `npm run build` runs the generator into public/ and then copies public/ into
 * dist/ alongside the Vite bundle. The template tests read the templates; this
 * script reads the built result, which is the only place where a page the
 * generator wrote, an asset nobody shipped, and a route the old shell still
 * owns can be told apart.
 *
 * Run it after a build:  npm run check:site
 *
 * Two kinds of finding, deliberately separated:
 *
 *   problems  the build must not ship as it stands (exit code 1)
 *   notes     true today, not yet a gate; printed so drift is visible
 *
 * T4 flips the meaning of `/`: today dist/index.html is the React shell and is
 * the only route with no source page in public/. Once public/index.html exists,
 * `/` becomes a generated page like any other, `id="root"` becomes a defect
 * there, and the `/*  →  /index.html 200` catch-all in _redirects starts
 * turning every unknown URL into a 200 copy of the homepage. The checks below
 * are written to notice exactly that on the run after the cutover.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/* vite.config.ts sets outDir to `../dist`, so the built tree sits beside the app
   folder, next to the config and package.json, not inside the app folder. An
   older build left a `AURA-eCommerce-Shop-main/dist/` behind from before that
   move (9 November 2026); reading it by mistake would compare today's pages with
   yesterday's. The script reads the real one and names the impostor. */
const appRoot = fileURLToPath(new URL('../', import.meta.url));
const repoRoot = fileURLToPath(new URL('../../', import.meta.url));
const publicDir = join(appRoot, 'public');
/* An alternative output directory may be passed as the first argument, which is
   how this checker is tested against a deliberately broken copy of a build. */
const distDir = process.argv[2] ? resolve(process.argv[2]) : join(repoRoot, 'dist');
const staleDist = join(appRoot, 'dist');

const problems = [];
const notes = [];
const problem = message => problems.push(message);

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap(entry => entry.isDirectory()
      ? walk(join(directory, entry.name))
      : [join(directory, entry.name)]);
}

const listing = directory => walk(directory)
  .map(file => relative(directory, file).split(sep).join('/'));

try {
  statSync(distDir);
} catch {
  console.error(`${distDir} does not exist. Run \`npm run build\` first.`);
  process.exit(1);
}

try {
  statSync(staleDist);
  notes.push(`AURA-eCommerce-Shop-main/dist/ is a leftover build from before outDir moved to ../dist; it is stale and not checked (safe to delete)`);
} catch {
  // Absent is the normal state.
}

const distFiles = new Set(listing(distDir));
const publicFiles = listing(publicDir);

/* ── 1. The build carried public/ over, byte for byte ────────────────────── */

for (const file of publicFiles) {
  if (!distFiles.has(file)) {
    problem(`dist/${file} is missing: the build did not copy it from public/`);
    continue;
  }
  const source = readFileSync(join(publicDir, file));
  const built = readFileSync(join(distDir, file));
  if (!source.equals(built)) problem(`dist/${file} differs from public/${file}`);
}

/* ── 2. Route inventory ──────────────────────────────────────────────────── */

/* A route is a directory with an index.html, plus `/` itself. A route whose
   file also exists in public/ is generated by us; a route that does not is
   produced by something else — today, the Vite shell. */
const routes = new Map();
for (const file of distFiles) {
  if (file === 'index.html') {
    routes.set('/', { file, generated: publicFiles.includes('index.html') });
  } else if (file.endsWith('/index.html')) {
    const route = `/${file.slice(0, -'index.html'.length)}`;
    routes.set(route, { file, generated: publicFiles.includes(file) });
  }
}
const generatedRoutes = [...routes].filter(([, info]) => info.generated).map(([route]) => route);
const shellRoutes = [...routes].filter(([, info]) => !info.generated).map(([route]) => route);

/* ── 3. Map a local URL to the file the browser would receive ────────────── */

function targetFor(url) {
  const path = url.split('#')[0].split('?')[0];
  if (!path.startsWith('/') || path.startsWith('//')) return null; // external, anchor, mailto
  let decoded;
  try {
    decoded = decodeURIComponent(path);
  } catch {
    return null;
  }
  if (decoded === '/') return 'index.html';
  if (decoded.endsWith('/')) return `${decoded.slice(1)}index.html`;
  if (/\.[a-z0-9]+$/i.test(decoded)) return decoded.slice(1);
  return `${decoded.slice(1)}/index.html`;
}

/* ── 4. Every generated page is a whole document ─────────────────────────── */

const TAILWIND_SIGNATURE = token =>
  token.includes(':') || token.includes('[') || token.includes(']');

let imageCount = 0;
let imageWithoutDimensions = 0;
let imageEager = 0;
const externalResources = new Set();
const languages = new Map();

for (const route of generatedRoutes) {
  const file = routes.get(route).file;
  const html = readFileSync(join(distDir, file), 'utf8');
  const where = `dist/${file}`;

  /* One site, one language declaration. A page that omits it, or disagrees with
     the other forty, is how a store ends up with half its pages announced in the
     wrong language to a screen reader or a crawler. */
  const lang = /<html[^>]*\slang="([^"]*)"/.exec(html);
  if (!lang) problem(`${where}: <html> has no lang attribute`);
  else languages.set(lang[1], [...(languages.get(lang[1]) || []), where]);

  const h1Count = (html.match(/<h1[\s>]/g) || []).length;
  if (h1Count !== 1) problem(`${where}: ${h1Count} <h1> elements, expected exactly 1`);

  const title = /<title>([^<]*)<\/title>/.exec(html);
  if (!title || !title[1].trim()) problem(`${where}: no <title>`);

  const description = /<meta name="description" content="([^"]*)"/.exec(html);
  if (!description || !description[1].trim()) problem(`${where}: no meta description`);

  // The static pages must not need a runtime. A mount point here means the
  // React bundle is still doing a job that the generated markup should own.
  if (/\sid="root"/.test(html)) problem(`${where}: ships the React mount point (id="root")`);

  for (const match of html.matchAll(/<script[^>]+src="(https?:[^"]+)"/g)) {
    problem(`${where}: loads a third-party script from ${match[1]}`);
  }

  /* Resources that the browser must fetch from another origin. An anchor to a
     supplier page is content, not a resource, so it is not listed here. */
  for (const match of html.matchAll(/<(?:link|img)[^>]+(?:href|src)="(https?:\/\/[^"]+)"/g)) {
    externalResources.add(match[1]);
  }

  // The generated markup carries semantic classes only. A Tailwind utility
  // here means the token layer was bypassed.
  for (const match of html.matchAll(/class="([^"]*)"/g)) {
    for (const token of match[1].split(/\s+/).filter(Boolean)) {
      if (TAILWIND_SIGNATURE(token)) problem(`${where}: Tailwind-style class "${token}"`);
    }
  }

  // Images: alt text is a gate; explicit dimensions are a note until T5.
  for (const match of html.matchAll(/<img\b[^>]*>/g)) {
    const tag = match[0];
    imageCount++;
    if (!/\salt="[^"]*"/.test(tag)) problem(`${where}: <img> without alt: ${tag.slice(0, 80)}`);
    if (!/\swidth="\d+"/.test(tag) || !/\sheight="\d+"/.test(tag)) imageWithoutDimensions++;
    if (!/\sloading="lazy"/.test(tag)) imageEager++;
  }

  // Every local reference must resolve to a file in the build.
  for (const match of html.matchAll(/\s(href|src|action)="([^"]*)"/g)) {
    const [, attribute, url] = match;
    const target = targetFor(url);
    if (target === null) continue;
    if (!distFiles.has(target)) problem(`${where}: ${attribute}="${url}" has no file in dist/`);
  }
}

if (imageWithoutDimensions) {
  notes.push(`${imageWithoutDimensions} of ${imageCount} images have no width/height (layout shift risk; promote to a problem at T5)`);
}
if (imageEager) notes.push(`${imageEager} of ${imageCount} images are not lazy-loaded`);
for (const url of externalResources) notes.push(`external resource: ${url}`);

if (languages.size > 1) {
  const disagreements = [...languages].map(([value, pages]) => `${value} (${pages.length} page${pages.length === 1 ? '' : 's'}, e.g. ${pages[0]})`);
  problem(`generated pages disagree on <html lang>: ${disagreements.join(' vs ')}`);
}

/* ── 5. The sitemap describes routes that exist, once each ───────────────── */

let sitemapRoutes = [];
try {
  const sitemap = readFileSync(join(distDir, 'sitemap.xml'), 'utf8');
  sitemapRoutes = [...sitemap.matchAll(/<loc>([^<]*)<\/loc>/g)].map(match => match[1]);
  if (!sitemapRoutes.length) problem('dist/sitemap.xml contains no <loc> entries');
  const seen = new Set();
  for (const loc of sitemapRoutes) {
    if (seen.has(loc)) problem(`dist/sitemap.xml lists ${loc} more than once`);
    seen.add(loc);
    const target = targetFor(loc);
    if (target === null || !distFiles.has(target)) problem(`dist/sitemap.xml lists ${loc}, which no page serves`);
  }
} catch {
  problem('dist/sitemap.xml is missing');
}

const unlisted = generatedRoutes.filter(route => !sitemapRoutes.includes(route));
for (const route of unlisted) notes.push(`${route} is a page but is not in the sitemap`);

/* ── 6. No catch-all rewrite may swallow a missing page ──────────────────── */

/* Until T4 this rule is what keeps the shell's client routes working. Once `/`
   serves a real page, the same rule answers 200 with that page to every URL that
   does not exist, which is how a storefront ends up with infinite soft 404s in a
   search index. The test is on the built artefact rather than on the source, so
   a build where `/` has already been replaced is caught even before the old
   source page is deleted. */
try {
  const redirects = readFileSync(join(distDir, '_redirects'), 'utf8');
  const catchAll = redirects
    .split('\n')
    .map(line => line.replace(/#.*$/, '').trim())
    .filter(Boolean)
    .map(line => line.split(/\s+/))
    .find(([from, to]) => from === '/*' && targetFor(to) === 'index.html');
  const home = distFiles.has('index.html') ? readFileSync(join(distDir, 'index.html'), 'utf8') : '';
  const homeIsRealPage = Boolean(home) && !/\sid="root"/.test(home);
  if (catchAll) {
    if (homeIsRealPage) {
      problem('dist/_redirects sends every unmatched URL to /index.html, which is now a real page: unknown URLs would return 200');
    } else {
      notes.push('dist/_redirects still has the SPA catch-all; remove it with the shell at T4/T8');
    }
  }
} catch {
  notes.push('no dist/_redirects (fine for static hosting that serves directories)');
}

/* ── Report ──────────────────────────────────────────────────────────────── */

const count = value => `${value} route${value === 1 ? '' : 's'}`;
console.log(`dist/: ${count(routes.size)} — ${generatedRoutes.length} generated, ${shellRoutes.length} not generated`);
console.log(`        ${distFiles.size} files, ${publicFiles.length} from public/, ${sitemapRoutes.length} sitemap entries`);
if (shellRoutes.length) console.log(`        not generated: ${shellRoutes.join(', ')}`);

for (const note of notes) console.log(`  note  ${note}`);

if (!problems.length) {
  console.log('\nAll checks passed.');
  process.exit(0);
}

console.log(`\n${problems.length} problem${problems.length === 1 ? '' : 's'}:`);
for (const message of problems) console.log(`  ✗ ${message}`);
process.exit(1);
